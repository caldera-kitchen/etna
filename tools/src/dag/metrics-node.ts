// Node-only: writes font-metrics.ts, the advance widths and x-height of every cached TrueType
// face (themes/.fonts, filled by `etna fonts`), which the chart layout measures text with. Run by
// `etna fonts metrics`; a test checks that the checked-in module is what this writes.

import { readFileSync } from 'node:fs';
import { basename, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import fontkit from '@cantoo/fontkit';

import { CHARS } from './metrics.ts';

/** The generated module, beside this file. */
export const FONT_METRICS_FILE = join(dirname(fileURLToPath(import.meta.url)), 'font-metrics.ts');

/** One face's advances: 1/1000 em, rounded, for every character of CHARS in order. */
export interface FaceMetrics {
  family: string;
  weight: number;
  file: string;
  advances: number[];
  /** Characters of CHARS the font has no glyph for: each is given the face's widest advance. */
  missing: string;
  /** The x-height in 1/1000 em to one decimal (OS/2 sxHeight, else the top of "x"); null when the font gives neither. */
  xHeight: number | null;
}

/** The advances and x-height of one TrueType file. */
export function faceMetrics(face: { family: string; weight: number; path: string }): FaceMetrics {
  const font = fontkit.create(readFileSync(face.path));
  if ('fonts' in font) throw new Error(`${face.path} is a font collection, not one face`);
  const scale = 1000 / font.unitsPerEm;
  const chars = [...CHARS];
  const found = chars.map((c) => {
    const cp = c.codePointAt(0)!;
    const glyph = font.hasGlyphForCodePoint(cp) ? font.glyphForCodePoint(cp) : null;
    return glyph ? Math.round(glyph.advanceWidth * scale) : null;
  });
  const widest = Math.max(...found.filter((a): a is number => a !== null));
  const os2 = (font as unknown as { 'OS/2'?: { xHeight?: number } })['OS/2'];
  const ex = font.hasGlyphForCodePoint(0x78) ? font.glyphForCodePoint(0x78) : null;
  const x = ex?.bbox.maxY ?? 0;
  const units = os2?.xHeight || x;
  return {
    family: face.family,
    weight: face.weight,
    file: basename(face.path),
    advances: found.map((a) => a ?? widest),
    missing: chars.filter((_, i) => found[i] === null).join(''),
    xHeight: units > 0 ? Math.round(units * scale * 10) / 10 : null,
  };
}

/**
 * The text of font-metrics.ts for the faces given: families in name order, weights in
 * ascending order, nothing that changes from run to run (no date), so the same files always
 * give the same module.
 */
export function fontMetricsModule(faces: readonly { family: string; weight: number; path: string }[]): string {
  const all = faces.map(faceMetrics).sort((a, b) => a.family.localeCompare(b.family) || a.weight - b.weight);
  const families = [...new Set(all.map((m) => m.family))];
  const out: string[] = [
    '// Generated by `etna fonts metrics` from the TrueType files in themes/.fonts/: do not edit.',
    '//',
    '// For each cached font family and weight, the advance width in 1/1000 em (the font\'s own',
    '// hmtx advance, rounded; no kerning) of every character of CHARS (metrics.ts), in that order.',
    '// A character the font has no glyph for is given the face\'s widest advance; the comment on',
    '// each face names its file and any such characters. FONT_X_HEIGHTS gives each face\'s',
    '// x-height (OS/2 sxHeight, else the top of "x") in 1/1000 em, to one decimal. measure.ts',
    '// reads both tables.',
    '',
    '/** Advances in 1/1000 em by family, then weight, in the order of CHARS. */',
    'export const FONT_METRICS: Readonly<Record<string, Readonly<Record<number, readonly number[]>>>> = {',
  ];
  for (const family of families) {
    out.push(`  '${family}': {`);
    for (const m of all.filter((x) => x.family === family)) {
      out.push(`    // ${m.file}${m.missing ? `; no glyph for ${m.missing}` : ''}`);
      out.push(`    ${m.weight}: [${m.advances.join(',')}],`);
    }
    out.push('  },');
  }
  out.push('};', '');
  out.push(
    '/** x-heights in 1/1000 em by family, then weight; a face whose font gives none is left out. */',
    'export const FONT_X_HEIGHTS: Readonly<Record<string, Readonly<Record<number, number>>>> = {',
  );
  for (const family of families) {
    const faces = all.filter((x) => x.family === family && x.xHeight !== null);
    if (faces.length > 0) out.push(`  '${family}': { ${faces.map((m) => `${m.weight}: ${m.xHeight}`).join(', ')} },`);
  }
  out.push('};', '');
  return out.join('\n');
}
